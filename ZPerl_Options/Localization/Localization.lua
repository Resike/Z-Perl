-- ZPerl.OptionsL: the options window's text, keyed by the English text itself (L["Advanced options"]). The settings
-- list (ZPerl_SettingsList.lua, ZPerl_SettingsListPages.lua) keeps its labels, tooltips, section and page names and
-- choices in English, because rows, shared controls and dropdown choices are matched by that text; the window passes
-- each string through this table only where it draws it. A string no locale file translates reads as itself.
--
-- The list below is every such string (of all clients: some rows exist only on retail, Mists or Classic), by page and
-- section, for translators to copy. Its values are the English text; a key missing here still reads as itself.
-- To translate, set the key in the Localization.<locale>.lua file of the language:
--   L["Advanced options"] = "Erweiterte Optionen"
-- A key with %s or %d keeps those placeholders, in the same order:
--   L["Needs: %s"] = "Benötigt: %s"
ZPerl.OptionsL = setmetatable({}, {__index = function(_, key) return key end})

